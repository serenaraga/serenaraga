-- A. Atomic Create Complete Booking
create or replace function rpc_create_booking_atomic(
    p_customer jsonb,
    p_booking jsonb,
    p_items jsonb
) returns jsonb as $$
declare
    v_customer_id bigint;
    v_booking_id bigint;
    v_item jsonb;
    v_total_price numeric := 0;
    v_first_service_id bigint := null;
    v_first_therapist_id bigint := null;
begin
    -- 1. Resolve or Create Customer by Phone
    if (p_customer->>'id') is not null and (p_customer->>'id') != '' and (p_customer->>'id') != 'null' then
        v_customer_id := (p_customer->>'id')::bigint;
    else
        select id into v_customer_id from customers 
        where right(regexp_replace(phone, '\D', '', 'g'), 8) = right(regexp_replace(p_customer->>'phone', '\D', '', 'g'), 8)
        limit 1;

        if v_customer_id is null then
            insert into customers (full_name, phone, address, notes)
            values (
                coalesce(p_customer->>'full_name', 'Pelanggan'),
                coalesce(p_customer->>'phone', '-'),
                coalesce(p_customer->>'address', coalesce(p_booking->>'service_address', '-')),
                p_customer->>'notes'
            ) returning id into v_customer_id;
        else
            update customers set
                full_name = coalesce(p_customer->>'full_name', full_name),
                address = coalesce(p_booking->>'service_address', address)
            where id = v_customer_id;
        end if;
    end if;

    -- 2. Compute summary values from items array
    if jsonb_array_length(p_items) > 0 then
        v_first_service_id := (p_items->0->>'service_id')::bigint;
        v_first_therapist_id := (p_items->0->>'therapist_id')::bigint;
        
        for v_item in select * from jsonb_array_elements(p_items)
        loop
            v_total_price := v_total_price + coalesce((v_item->>'price')::numeric, 0);
        end loop;
    else
        v_total_price := coalesce((p_booking->>'total_price')::numeric, 0);
    end if;

    -- 3. Insert Master Booking
    insert into bookings (
        customer_id,
        service_id,
        therapist_id,
        booking_date,
        booking_time,
        service_address,
        total_price,
        status,
        payment_method,
        payment_status,
        special_requests
    ) values (
        v_customer_id,
        v_first_service_id,
        v_first_therapist_id,
        coalesce((p_booking->>'booking_date')::date, current_date),
        coalesce(p_booking->>'booking_time', '10:00'),
        coalesce(p_booking->>'service_address', '-'),
        v_total_price,
        coalesce(p_booking->>'status', 'pending'),
        coalesce(p_booking->>'payment_method', 'cash'),
        coalesce(p_booking->>'payment_status', 'unpaid'),
        p_booking->>'special_requests'
    ) returning id into v_booking_id;

    -- 4. Batch Insert Relational Booking Items
    for v_item in select * from jsonb_array_elements(p_items)
    loop
        insert into booking_items (
            booking_id,
            service_id,
            service_name_snapshot,
            therapist_id,
            therapist_name_snapshot,
            price,
            commission_rate_snapshot,
            consumables_cost_snapshot,
            duration_minutes_snapshot
        ) values (
            v_booking_id,
            (v_item->>'service_id')::bigint,
            coalesce(v_item->>'service_name', 'Layanan'),
            (v_item->>'therapist_id')::bigint,
            v_item->>'therapist_name',
            coalesce((v_item->>'price')::numeric, 0),
            coalesce((v_item->>'rate')::numeric, 60),
            coalesce((v_item->>'bhp')::numeric, 0),
            coalesce((v_item->>'duration_minutes')::integer, 60)
        );
    end loop;

    return jsonb_build_object(
        'success', true,
        'booking_id', v_booking_id,
        'customer_id', v_customer_id,
        'total_price', v_total_price
    );
end;
$$ language plpgsql security definer set search_path = public;

