-- 14. Tabel Therapist Payouts (Rekap Bagi Hasil & Slip Pembayaran Terapis)
create table if not exists therapist_payouts (
    id bigint generated by default as identity primary key,
    payout_number text unique not null,
    therapist_id bigint references therapists(id) on delete set null,
    therapist_name text not null,
    period_type text default 'monthly', -- 'daily', 'weekly', 'monthly', 'custom'
    period_start date not null,
    period_end date not null,
    total_bookings integer not null default 0,
    gross_amount numeric not null default 0,
    commission_rate numeric not null default 60,
    therapist_fee numeric not null default 0,
    company_fee numeric not null default 0,
    bonus_amount numeric default 0,
    deduction_amount numeric default 0,
    net_amount numeric not null default 0,
    bank_name text default 'BCA',
    bank_account_number text,
    bank_account_name text,
    payment_status text default 'paid', -- 'pending', 'paid'
    payment_date date default current_date,
    notes text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table therapist_payouts enable row level security;
drop policy if exists "Allow anon full access on therapist_payouts" on therapist_payouts;
create policy "Allow anon full access on therapist_payouts" on therapist_payouts for all using (true) with check (true);

create index if not exists idx_payouts_therapist on therapist_payouts(therapist_id);
create index if not exists idx_payouts_number on therapist_payouts(payout_number);
create index if not exists idx_payouts_period on therapist_payouts(period_start, period_end);

