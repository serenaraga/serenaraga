-- Setup Supabase Storage Buckets untuk Foto & Dokumen Terapis
insert into storage.buckets (id, name, public)
values 
    ('therapist-photos', 'therapist-photos', true),
    ('therapist-documents', 'therapist-documents', true)
on conflict (id) do update set public = true;

-- Storage RLS Policies
drop policy if exists "Allow public read on therapist photos" on storage.objects;
create policy "Allow public read on therapist photos" on storage.objects for select using (bucket_id in ('therapist-photos', 'therapist-documents'));

drop policy if exists "Allow authenticated and anon uploads to therapist storage" on storage.objects;
create policy "Allow authenticated and anon uploads to therapist storage" on storage.objects for insert with check (bucket_id in ('therapist-photos', 'therapist-documents'));

drop policy if exists "Allow delete and update on therapist storage" on storage.objects;
create policy "Allow delete and update on therapist storage" on storage.objects for all using (bucket_id in ('therapist-photos', 'therapist-documents'));

-- 4. Tabel Customers (Data Pelanggan)
create table if not exists customers (
    id bigint generated by default as identity primary key,
    full_name text not null,
    phone text not null,
    email text,
    address text not null,
    city_area text,
    notes text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 5. Tabel Bookings (Pemesanan Layanan Home Massage)
create table if not exists bookings (
    id bigint generated by default as identity primary key,
    customer_id bigint references customers(id) on delete cascade,
    service_id bigint references services(id) on delete set null,
    therapist_id bigint references therapists(id) on delete set null,
    booking_date date not null default current_date,
    booking_time text not null default '10:00',
    service_address text not null,
    total_price numeric not null default 150000,
    status text default 'pending', -- 'pending', 'confirmed', 'on_the_way', 'in_progress', 'completed', 'cancelled'
    payment_method text default 'cash', -- 'cash', 'bank_transfer', 'qris', 'credit_card'
    payment_status text default 'unpaid', -- 'unpaid', 'paid', 'refunded'
    special_requests text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 6. Tabel Invoices (Nota & Checkout Pembayaran)
create table if not exists invoices (
    id bigint generated by default as identity primary key,
    invoice_number text unique not null,
    booking_id bigint references bookings(id) on delete set null,
    customer_id bigint references customers(id) on delete set null,
    customer_name text not null,
    customer_phone text not null,
    service_id bigint references services(id) on delete set null,
    service_name text not null,
    therapist_id bigint references therapists(id) on delete set null,
    therapist_name text,
    booking_date date,
    booking_time text,
    service_address text,
    subtotal numeric not null default 0,
    discount numeric default 0,
    transport_fee numeric default 0,
    total_amount numeric not null default 0,
    payment_method text default 'cash', -- 'cash', 'qris', 'bank_transfer'
    payment_status text default 'unpaid', -- 'unpaid', 'paid', 'refunded'
    notes text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 7. Tabel Reviews (Ulasan & Rating Pelanggan)
create table if not exists reviews (
    id bigint generated by default as identity primary key,
    booking_id bigint references bookings(id) on delete cascade,
    invoice_id bigint references invoices(id) on delete set null,
    therapist_id bigint references therapists(id) on delete set null,
    customer_name text,
    rating integer not null check (rating >= 1 and rating <= 5),
    comment text,
    is_read boolean default false,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

