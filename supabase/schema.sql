-- 1. Enable UUID Extension
create extension if not exists "uuid-ossp";

-- 2. Tabel Services (Katalog Layanan Pijat)
create table if not exists services (
    id bigint generated by default as identity primary key,
    name text not null,
    category text default 'Body Massage',
    description text,
    duration_minutes integer not null default 60,
    price numeric not null default 150000,
    image_url text,
    is_active boolean default true,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. Tabel Therapists (Daftar & Manajemen Terapis Lengkap)
create table if not exists therapists (
    id bigint generated by default as identity primary key,
    name text not null,
    phone text not null,
    gender text default 'Female', -- 'Female', 'Male'
    birth_date date,
    nik text, -- Nomor Induk Kependudukan (16 Digit KTP)
    ktp_photo_url text, -- Foto KTP Kualitas HD untuk Verifikasi
    domicile_address text, -- Alamat Domisili Lengkap Terapis
    emergency_contact_name text, -- Nama Kontak Darurat (Keluarga)
    emergency_contact_phone text, -- No HP Kontak Darurat
    specialties text,
    experience_years integer default 1,
    photo_url text, -- Foto Profil Seragam Terapis
    cv_url text, -- Dokumen CV / Resume (PDF / Gambar)
    certificate_url text, -- Sertifikat Kompetensi Pijat / BNSP
    rating numeric(2,1) default 5.0,
    status text default 'available', -- 'available', 'on_duty', 'off_duty', 'pending_verification'
    commission_rate numeric not null default 60, -- Persentase bagi hasil terapis (contoh: 60%)
    bank_name text default 'BCA', -- Nama Bank untuk Payroll
    bank_account_number text, -- Nomor Rekening
    bank_account_name text, -- Nama Pemilik Rekening
    coverage_areas text default 'Jakarta Selatan, Tangerang Selatan', -- Area Jangkauan Layanan
    joined_date date default current_date, -- Tanggal Mulai Bergabung
    notes text, -- Catatan Internal HR / Admin
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

