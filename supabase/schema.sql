    customer_id bigint references customers(id) on delete set null,
    customer_name text not null,
    customer_phone text not null,
    service_id bigint references services(id) on delete set null,
    service_name text not null,
    therapist_id bigint references therapists(id) on delete set null,
    therapist_name text,
    booking_date date,
    booking_time text,
    service_address text,
    subtotal numeric not null default 0,
    discount numeric default 0,
    transport_fee numeric default 0,
    additional_charge numeric default 0,
    additional_charge_description text,
    total_amount numeric not null default 0,
    payment_method text default 'cash', -- 'cash', 'qris', 'bank_transfer'
    payment_status text default 'unpaid', -- 'unpaid', 'paid', 'refunded'
