    booking_time text not null default '10:00',
    service_address text not null,
    total_price numeric not null default 150000,
    status text default 'pending', -- 'pending', 'confirmed', 'on_the_way', 'in_progress', 'completed', 'cancelled'
    payment_method text default 'cash', -- 'cash', 'bank_transfer', 'qris', 'credit_card'
    payment_status text default 'unpaid', -- 'unpaid', 'paid', 'refunded'
