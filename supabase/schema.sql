-- A. RPC: Atomic Create Complete Booking
create or replace function rpc_create_booking_atomic(
    p_customer jsonb,
    p_booking jsonb,
    p_items jsonb
) returns jsonb as $$
declare
    v_customer_id bigint;
    v_booking_id bigint;
    v_item jsonb;
    v_total_price numeric := 0;
    v_first_service_id bigint := null;
    v_first_therapist_id bigint := null;
begin
    -- 1. Resolve or Create Customer by Phone
    if (p_customer->>'id') is not null and (p_customer->>'id') != '' and (p_customer->>'id') != 'null' then
        v_customer_id := (p_customer->>'id')::bigint;
    else
        select id into v_customer_id from customers 
        where right(regexp_replace(phone, '\D', '', 'g'), 8) = right(regexp_replace(p_customer->>'phone', '\D', '', 'g'), 8)
        limit 1;

        if v_customer_id is null then
            insert into customers (full_name, phone, address, notes)
            values (
                coalesce(p_customer->>'full_name', 'Pelanggan'),
                coalesce(p_customer->>'phone', '-'),
                coalesce(p_customer->>'address', coalesce(p_booking->>'service_address', '-')),
                p_customer->>'notes'
            ) returning id into v_customer_id;
        else
            update customers set
                full_name = coalesce(p_customer->>'full_name', full_name),
                address = coalesce(p_booking->>'service_address', address)
            where id = v_customer_id;
        end if;
    end if;

    -- 2. Compute summary values from items array
    if jsonb_array_length(p_items) > 0 then
        v_first_service_id := (p_items->0->>'service_id')::bigint;
        v_first_therapist_id := (p_items->0->>'therapist_id')::bigint;
        
        for v_item in select * from jsonb_array_elements(p_items)
        loop
            v_total_price := v_total_price + coalesce((v_item->>'price')::numeric, 0);
        end loop;
    else
        v_total_price := coalesce((p_booking->>'total_price')::numeric, 0);
    end if;

    -- 3. Insert Master Booking
    insert into bookings (
        customer_id,
        service_id,
        therapist_id,
        booking_date,
        booking_time,
        service_address,
        total_price,
        status,
        payment_method,
        payment_status,
        special_requests
    ) values (
        v_customer_id,
        v_first_service_id,
        v_first_therapist_id,
        coalesce((p_booking->>'booking_date')::date, current_date),
        coalesce(p_booking->>'booking_time', '10:00'),
        coalesce(p_booking->>'service_address', '-'),
        v_total_price,
        coalesce(p_booking->>'status', 'pending'),
        coalesce(p_booking->>'payment_method', 'cash'),
        coalesce(p_booking->>'payment_status', 'unpaid'),
        p_booking->>'special_requests'
    ) returning id into v_booking_id;

    -- 4. Batch Insert Relational Booking Items
    for v_item in select * from jsonb_array_elements(p_items)
    loop
        insert into booking_items (
            booking_id,
            service_id,
            service_name_snapshot,
            therapist_id,
            therapist_name_snapshot,
            price,
            commission_rate_snapshot,
            consumables_cost_snapshot,
            duration_minutes_snapshot
        ) values (
            v_booking_id,
            (v_item->>'service_id')::bigint,
            coalesce(v_item->>'service_name', 'Layanan'),
            (v_item->>'therapist_id')::bigint,
            v_item->>'therapist_name',
            coalesce((v_item->>'price')::numeric, 0),
            coalesce((v_item->>'rate')::numeric, 60),
            coalesce((v_item->>'bhp')::numeric, 0),
            coalesce((v_item->>'duration_minutes')::integer, 60)
        );
    end loop;

    return jsonb_build_object(
        'success', true,
        'booking_id', v_booking_id,
        'customer_id', v_customer_id,
        'total_price', v_total_price
    );
end;
$$ language plpgsql security definer;

-- B. RPC: Atomic Create Complete Invoice
create or replace function rpc_create_invoice_atomic(
    p_invoice jsonb,
    p_items jsonb
) returns jsonb as $$
declare
    v_invoice_id bigint;
    v_item jsonb;
    v_invoice_number text;
begin
    v_invoice_number := coalesce(p_invoice->>'invoice_number', 'INV-' || to_char(now(), 'YYYYMMDD-HH24MISS'));

    -- 1. Insert Master Invoice
    insert into invoices (
        invoice_number,
        booking_id,
        customer_id,
        customer_name,
        customer_phone,
        service_id,
        service_name,
        therapist_id,
        therapist_name,
        booking_date,
        booking_time,
        service_address,
        subtotal,
        discount,
        transport_fee,
        total_amount,
        payment_method,
        payment_status,
        notes
    ) values (
        v_invoice_number,
        (p_invoice->>'booking_id')::bigint,
        (p_invoice->>'customer_id')::bigint,
        coalesce(p_invoice->>'customer_name', 'Pelanggan'),
        coalesce(p_invoice->>'customer_phone', '-'),
        (p_invoice->>'service_id')::bigint,
        coalesce(p_invoice->>'service_name', 'Layanan'),
        (p_invoice->>'therapist_id')::bigint,
        p_invoice->>'therapist_name',
        (p_invoice->>'booking_date')::date,
        p_invoice->>'booking_time',
        p_invoice->>'service_address',
        coalesce((p_invoice->>'subtotal')::numeric, 0),
        coalesce((p_invoice->>'discount')::numeric, 0),
        coalesce((p_invoice->>'transport_fee')::numeric, 0),
        coalesce((p_invoice->>'total_amount')::numeric, 0),
        coalesce(p_invoice->>'payment_method', 'cash'),
        coalesce(p_invoice->>'payment_status', 'unpaid'),
        p_invoice->>'notes'
    ) returning id into v_invoice_id;

    -- 2. Insert Line Items
    if p_items is not null and jsonb_array_length(p_items) > 0 then
        for v_item in select * from jsonb_array_elements(p_items)
        loop
            insert into invoice_items (
                invoice_id,
                service_id,
                service_name_snapshot,
                therapist_id,
                therapist_name_snapshot,
                price,
                commission_rate_snapshot,
                consumables_cost_snapshot,
                therapist_fee_calculated
            ) values (
                v_invoice_id,
                (v_item->>'service_id')::bigint,
                coalesce(v_item->>'service_name', coalesce(v_item->>'name', 'Layanan')),
                (v_item->>'therapist_id')::bigint,
                coalesce(v_item->>'therapist_name', v_item->>'therapist'),
                coalesce((v_item->>'price')::numeric, 0),
                coalesce((v_item->>'rate')::numeric, 60),
                coalesce((v_item->>'bhp')::numeric, 0),
                coalesce((v_item->>'commission')::numeric, 0)
            );
        end loop;
    end if;

    -- 3. Update Booking payment status if booking_id exists
    if (p_invoice->>'booking_id') is not null and (p_invoice->>'booking_id') != '' and (p_invoice->>'booking_id') != 'none' then
        update bookings set
            payment_status = coalesce(p_invoice->>'payment_status', payment_status),
            status = coalesce(p_invoice->>'booking_status', case when (p_invoice->>'payment_status') = 'paid' then 'completed' else status end)
        where id = (p_invoice->>'booking_id')::bigint;
    end if;

    return jsonb_build_object(
        'success', true,
        'invoice_id', v_invoice_id,
        'invoice_number', v_invoice_number
    );
end;
$$ language plpgsql security definer;

-- C. RPC: Ultra Fast Dashboard Analytics
create or replace function rpc_get_dashboard_analytics(
    p_start_date date default (current_date - interval '30 days')::date,
    p_end_date date default current_date
) returns jsonb as $$
declare
    v_total_revenue numeric := 0;
    v_paid_invoices integer := 0;
    v_total_bookings integer := 0;
    v_completed_bookings integer := 0;
    v_top_services jsonb;
    v_top_therapists jsonb;
begin
    -- 1. Revenue and Invoice metrics
    select 
        coalesce(sum(total_amount), 0),
        count(id)
    into v_total_revenue, v_paid_invoices
    from invoices
    where payment_status = 'paid'
      and (booking_date between p_start_date and p_end_date or (booking_date is null and created_at::date between p_start_date and p_end_date));

    -- 2. Bookings metrics
    select 
        count(id),
        count(id) filter (where status in ('completed', 'confirmed'))
    into v_total_bookings, v_completed_bookings
    from bookings
    where booking_date between p_start_date and p_end_date;

    -- 3. Top Services by volume
    select jsonb_agg(sub) into v_top_services from (
        select service_name as name, count(*) as count, sum(total_amount) as revenue
        from invoices
        where payment_status = 'paid'
          and (booking_date between p_start_date and p_end_date or (booking_date is null and created_at::date between p_start_date and p_end_date))
        group by service_name
        order by count desc
        limit 5
    ) sub;

    -- 4. Top Therapists by volume
    select jsonb_agg(sub) into v_top_therapists from (
        select therapist_name as name, count(*) as count, sum(total_amount) as revenue
        from invoices
        where payment_status = 'paid'
          and therapist_name is not null
          and (booking_date between p_start_date and p_end_date or (booking_date is null and created_at::date between p_start_date and p_end_date))
        group by therapist_name
        order by count desc
        limit 5
    ) sub;

    return jsonb_build_object(
        'total_revenue', v_total_revenue,
        'paid_invoices', v_paid_invoices,
        'total_bookings', v_total_bookings,
        'completed_bookings', v_completed_bookings,
        'top_services', coalesce(v_top_services, '[]'::jsonb),
        'top_therapists', coalesce(v_top_therapists, '[]'::jsonb)
    );
end;
$$ language plpgsql security definer;

