-- 17. SECURE AUTHENTICATION RPC (PREVENTS DUMPING PASSWORDS)
-- =========================================================
create or replace function rpc_authenticate_user(
    p_identifier text,
    p_password text
) returns jsonb as $$
declare
    v_user record;
    v_clean_id text := trim(lower(coalesce(p_identifier, '')));
    v_clean_pass text := trim(coalesce(p_password, ''));
    v_admin_passwords text[] := array[
        'adminserena2026',
        'admin123!',
        'admin123',
        'admin'
    ];
begin
    if v_clean_id = '' or v_clean_pass = '' then
        return null;
    end if;

    -- Lookup user by username or email
    select id, username, email, full_name, password_hash, role, avatar_url, is_active
    into v_user
    from app_users
    where lower(username) = v_clean_id
       or lower(email) = v_clean_id
       or lower(username) = v_clean_id || '.com'
       or lower(email) = v_clean_id || '.com'
    limit 1;

    if v_user.id is not null then
        -- Check password match (Exact or admin master password)
        if v_user.password_hash = v_clean_pass 
           or lower(v_user.password_hash) = lower(v_clean_pass)
           or (v_user.role = 'admin' and lower(v_clean_pass) = any(v_admin_passwords)) then
            
            return jsonb_build_object(
                'id', v_user.id,
                'username', v_user.username,
                'email', coalesce(v_user.email, v_user.username),
                'full_name', v_user.full_name,
                'role', v_user.role,
                'avatar_url', v_user.avatar_url,
                'is_active', coalesce(v_user.is_active, true)
            );
        end if;
    end if;

    -- Fallback owner login
    if (v_clean_id = 'admin' or v_clean_id = 'admin@serenaraga' or v_clean_id = 'admin@serenaraga.com') 
       and lower(v_clean_pass) = any(v_admin_passwords) then
        return jsonb_build_object(
            'id', 'admin-owner',
            'username', 'admin@serenaraga.com',
            'email', 'admin@serenaraga.com',
            'full_name', 'Owner / Super Admin',
            'role', 'admin',
            'avatar_url', 'https://images.unsplash.com/photo-1534528741775-53994a69daeb?w=150&auto=format&fit=crop&q=80',
            'is_active', true
        );
    end if;

    return null;
end;
$$ language plpgsql security definer set search_path = public;

